  function driver(root, frame) {
    var on = false, last = 0, raf = 0;
    function loop(now) { var dt = Math.min(.05, (now - last) / 1000 || 0); last = now; frame(dt, now); raf = requestAnimationFrame(loop); }
    function set(v) { if (v === on) return; on = v; if (on) { last = performance.now(); raf = requestAnimationFrame(loop); } else cancelAnimationFrame(raf); }
    if ('IntersectionObserver' in window) new IntersectionObserver(function (es) { set(es[0].isIntersecting); }, { rootMargin: '80px 0px' }).observe(root);
    else set(true);
    document.addEventListener('visibilitychange', function () { if (document.hidden) set(false); });
  }

