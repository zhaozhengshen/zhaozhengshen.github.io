  Crane.prototype.step = function (dt, nextJob, speed) {
    this.scale += (this.target - this.scale) * Math.min(1, dt * 5);
    if (this.phase === 'idle' || this.phase === 'pick' || this.phase === 'drop') {
      this.wait -= dt;
      if (this.wait <= 0) {
        if (this.phase === 'idle') {
          this.job = nextJob(this);
          if (this.job) { this.phase = 'toSrc'; this.tgt = this.polar(this.job.src); }
          else this.wait = .4;
        } else if (this.phase === 'pick') {
          this.phase = 'toDst'; this.tgt = this.polar(this.job.dst); this.load.style.fill = COL[kind(this.job.fac)]; this.load.style.opacity = 1;
          this.trailFrom = this.job.src;
        } else {
          this.phase = 'idle'; this.wait = .05; this.load.style.opacity = 0;
          if (this.job.done) this.job.done();
          this.trail(this.trailFrom, this.job.dst);
        }
      }
    } else {
      var w = 120 * speed * dt, v = 70 * speed * dt, d = angDiff(this.th, this.tgt[0]);
      this.th += Math.abs(d) <= w ? d : Math.sign(d) * w;
      var dr = this.tgt[1] - this.rho;
      this.rho += Math.abs(dr) <= v ? dr : Math.sign(dr) * v;
      if (Math.abs(angDiff(this.th, this.tgt[0])) < .01 && Math.abs(this.tgt[1] - this.rho) < .01) {
        this.phase = this.phase === 'toSrc' ? 'pick' : 'drop'; this.wait = .22 / speed;
      }
    }
    var c = P(this.xy[0], this.xy[1]);
    this.g.setAttribute('transform', 'translate(' + c[0] + ',' + c[1] + ') scale(' + this.scale.toFixed(3) + ')');
    this.jib.setAttribute('transform', 'rotate(' + (-this.th).toFixed(2) + ')');
    this.trol.setAttribute('transform', 'translate(' + this.rho.toFixed(2) + ',0)');
    this.cov.setAttribute('r', (this.r * this.scale).toFixed(2));
    this.cov.style.opacity = this.scale;
  };
